import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { converter } from "culori";
import { tokens } from "../../src/core/theme/tokens.ts";

const outFile = fileURLToPath(
	new URL("../../src/app/theme/tokens.css", import.meta.url),
);
const displayPath = "src/app/theme/tokens.css";
const toOklch = converter("oklch");

const semantic = [
	["background", tokens.color.background],
	["foreground", tokens.color.foreground],
	["card", tokens.color.card],
	["card-foreground", tokens.color.cardForeground],
	["muted", tokens.color.muted],
	["muted-foreground", tokens.color.mutedForeground],
	["border", tokens.color.border],
	["primary", tokens.color.primary],
	["primary-foreground", tokens.color.primaryForeground],
	["destructive", tokens.color.destructive],
];

const fingers = [
	["finger-l-pinky", tokens.finger.lPinky],
	["finger-l-ring", tokens.finger.lRing],
	["finger-l-middle", tokens.finger.lMiddle],
	["finger-l-index", tokens.finger.lIndex],
	["finger-r-index", tokens.finger.rIndex],
	["finger-r-middle", tokens.finger.rMiddle],
	["finger-r-ring", tokens.finger.rRing],
	["finger-r-pinky", tokens.finger.rPinky],
	["finger-thumb", tokens.finger.thumb],
];

const meaning = [
	["text-active", tokens.meaning.textActive],
	["beacon", tokens.meaning.beacon],
	["shield", tokens.meaning.shield],
	["static", tokens.meaning.static],
];

const typeSteps = [
	["type-target", tokens.type.target],
	["type-prose", tokens.type.prose],
	["display-xl", tokens.type.displayXl],
	["display-lg", tokens.type.displayLg],
	["display-md", tokens.type.displayMd],
	["ui-lg", tokens.type.uiLg],
	["ui-md", tokens.type.uiMd],
	["ui-sm", tokens.type.uiSm],
];

function round5(value) {
	if (typeof value !== "number" || !Number.isFinite(value)) {
		return "0.00000";
	}
	return value.toFixed(5);
}

function oklchOf(hex, alpha) {
	const converted = toOklch(hex);
	let hue = converted.h ?? 0;
	if (!Number.isFinite(hue)) {
		hue = 0;
	}
	hue = ((hue % 360) + 360) % 360;
	const channels = `oklch(${round5(converted.l)} ${round5(converted.c)} ${round5(hue)})`;
	if (alpha === undefined || alpha === 1) {
		return channels;
	}
	return `${channels.slice(0, -1)} / ${Math.round(alpha * 100)}%)`;
}

function colorDecl(name, color) {
	return `--${name}: ${oklchOf(color.hex, color.alpha)};`;
}

function percent(alpha) {
	return Math.round(alpha * 100);
}

function glowValue(glow) {
	return `${glow.x} ${glow.y} ${glow.blurPx}px color-mix(in oklch, var(--accent) ${percent(glow.alpha)}%, transparent)`;
}

function seconds(ms) {
	return `${ms / 1000}s`;
}

function easingValue(easing) {
	if (typeof easing === "string") {
		return easing;
	}
	return `cubic-bezier(${easing.join(", ")})`;
}

function stylesheet() {
	const lines = ["/* Generated by pnpm tokens. Do not edit. */", ""];

	const theme = [
		...semantic.map(([name]) => `--color-${name}: var(--${name});`),
		"--color-accent: var(--accent);",
		"--color-ring: var(--ring);",
		...fingers.map(([name]) => `--color-${name}: var(--${name});`),
		...meaning.map(([name]) => `--color-${name}: var(--${name});`),
		`--font-mono: "${tokens.font.mono}", ui-monospace, monospace;`,
		`--font-display: "${tokens.font.display}", ui-sans-serif, sans-serif;`,
		`--font-ui: "${tokens.font.ui}", ui-sans-serif, sans-serif;`,
	];
	for (const [name, step] of typeSteps) {
		theme.push(`--text-${name}: ${step.sizePx}px;`);
		theme.push(`--text-${name}--line-height: ${step.lineHeightPx}px;`);
	}
	theme.push(
		"--radius-lg: var(--radius);",
		"--shadow-glow-sm: var(--glow-sm);",
		"--shadow-glow-md: var(--glow-md);",
		"--shadow-glow-lg: var(--glow-lg);",
		`--shadow-focus: 0 0 0 ${tokens.surface.focus.ringPx}px var(--ring), var(--glow-sm);`,
		`--ease-micro: ${easingValue(tokens.motion.micro.easing)};`,
		`--ease-scene: ${easingValue(tokens.motion.scene.easing)};`,
	);

	const home = tokens.zone[0];
	const root = [
		...semantic.map(([name, color]) => colorDecl(name, color)),
		...fingers.map(([name, color]) => colorDecl(name, color)),
		...meaning.map(([name, color]) => colorDecl(name, color)),
		"--accent: var(--zone-accent);",
		"--ring: var(--zone-accent);",
		colorDecl("zone-bg", home.background),
		colorDecl("zone-accent", home.accent),
		`--radius: ${tokens.radiusPx}px;`,
		`--glow-sm: ${glowValue(tokens.surface.glowSm)};`,
		`--glow-md: ${glowValue(tokens.surface.glowMd)};`,
		`--glow-lg: ${glowValue(tokens.surface.glowLg)};`,
		`--glass-blur: ${tokens.surface.glass.blurPx}px;`,
		`--glass-border-width: ${tokens.surface.glass.borderPx}px;`,
		`--glass-border-color: color-mix(in oklch, var(--border) ${percent(tokens.surface.glass.borderAlpha)}%, transparent);`,
		`--motion-micro-duration: ${tokens.motion.micro.durationMs}ms;`,
		`--motion-standard-duration: ${tokens.motion.standard.durationMs}ms;`,
		`--motion-standard-stiffness: ${tokens.motion.standard.stiffness};`,
		`--motion-standard-damping: ${tokens.motion.standard.damping};`,
		`--motion-scene-duration: ${tokens.motion.scene.durationMs}ms;`,
		`--motion-celebrate-min: ${seconds(tokens.motion.celebrate.minMs)};`,
		`--motion-celebrate-max: ${seconds(tokens.motion.celebrate.maxMs)};`,
		`--z-canvas: ${tokens.layer.canvas};`,
		`--z-hud: ${tokens.layer.hud};`,
		`--z-overlay: ${tokens.layer.overlay};`,
		`--z-modal: ${tokens.layer.modal};`,
		`--z-toast: ${tokens.layer.toast};`,
		`--icon-stroke: ${tokens.icon.strokeWidth};`,
		...tokens.icon.sizesPx.map((size) => `--icon-size-${size}: ${size}px;`),
	];

	pushBlock(lines, "@theme inline", theme);
	pushBlock(lines, ":root", root);
	for (const zone of tokens.zone) {
		const declarations = [
			colorDecl("zone-bg", zone.background),
			colorDecl("zone-accent", zone.accent),
		];
		if (zone.accent2 !== undefined) {
			declarations.push(colorDecl("zone-accent-2", zone.accent2));
		}
		pushBlock(lines, `[data-zone="${zone.id}"]`, declarations);
	}

	return lines.join("\n");
}

function pushBlock(lines, selector, declarations) {
	lines.push(`${selector} {`);
	for (const declaration of declarations) {
		lines.push(`\t${declaration}`);
	}
	lines.push("}", "");
}

const next = stylesheet();
const check = process.argv.includes("--check");
let current = null;
try {
	current = readFileSync(outFile, "utf8");
} catch (error) {
	if (error.code !== "ENOENT") {
		throw error;
	}
}

if (current === next) {
	console.log(`fresh ${displayPath}`);
	process.exit(0);
}

if (check) {
	console.error(`${displayPath} is stale. Run pnpm tokens.`);
	process.exit(1);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, next);
console.log(`wrote ${displayPath}`);
